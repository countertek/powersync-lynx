import * as esbuild from "esbuild";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outfile = path.join(root, "dist/web-host/factory.js");

export async function bundleWebHostFactory() {
  fs.mkdirSync(path.dirname(outfile), { recursive: true });
  await esbuild.build({
    absWorkingDir: root,
    entryPoints: [path.join(root, "src/web-host/factory.ts")],
    bundle: true,
    format: "esm",
    platform: "neutral",
    target: "es2022",
    outfile,
    legalComments: "none",
    logLevel: "silent",
  });
  const generated = fs.readFileSync(outfile, "utf8");
  fs.writeFileSync(
    outfile,
    `/* generated by scripts/bundle-web-host-factory.mjs; do not edit */\n${generated}`,
  );
  return outfile;
}

const invoked = process.argv[1] != null && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (invoked) {
  await bundleWebHostFactory();
}
